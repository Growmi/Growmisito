function growmiApplyLang(lang){
  document.documentElement.setAttribute('lang', lang);
  document.querySelectorAll('[data-i18n]').forEach(function(el){
    var key = el.getAttribute('data-i18n');
    var val = GROWMI_I18N[lang][key];
    if(val !== undefined){ el.innerHTML = val; }
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(function(el){
    var key = el.getAttribute('data-i18n-placeholder');
    var val = GROWMI_I18N[lang][key];
    if(val !== undefined){ el.setAttribute('placeholder', val); }
  });
  document.querySelectorAll('.lang-switch button').forEach(function(btn){
    btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
  });
  try{ localStorage.setItem('growmi_lang', lang); }catch(e){}
}

function growmiInitLang(){
  var saved = 'it';
  try{ saved = localStorage.getItem('growmi_lang') || 'it'; }catch(e){}
  growmiApplyLang(saved);
  document.querySelectorAll('.lang-switch button').forEach(function(btn){
    btn.addEventListener('click', function(){
      growmiApplyLang(btn.getAttribute('data-lang'));
    });
  });
}

document.addEventListener('DOMContentLoaded', growmiInitLang);

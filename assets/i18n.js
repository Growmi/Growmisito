function growmiApplyLang(lang){
  document.documentElement.setAttribute('lang', lang);
  document.querySelectorAll('[data-i18n]').forEach(function(el){
    var key = el.getAttribute('data-i18n');
    var val = GROWMI_I18N[lang][key];
    if(val !== undefined){ el.innerHTML = val; }
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(function(el){
    var key = el.getAttribute('data-i18n-placeholder');
    var val = GROWMI_I18N[lang][key];
    if(val !== undefined){ el.setAttribute('placeholder', val); }
  });
  document.querySelectorAll('.lang-switch button').forEach(function(btn){
    btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
  });
  try{ localStorage.setItem('growmi_lang', lang); }catch(e){}
}

function growmiInitLang(){
  var saved = 'it';
  try{ saved = localStorage.getItem('growmi_lang') || 'it'; }catch(e){}
  growmiApplyLang(saved);
  document.querySelectorAll('.lang-switch button').forEach(function(btn){
    btn.addEventListener('click', function(){
      growmiApplyLang(btn.getAttribute('data-lang'));
    });
  });
}

function growmiInitNavToggle(){
  document.querySelectorAll('.nav-toggle').forEach(function(toggle){
    var nav = toggle.closest('nav');
    var navlinks = nav ? nav.querySelector('.navlinks') : null;
    if(!navlinks) return;
    // la chiusura resta leggermente più lenta dell'apertura: si aggiunge .closing (che riproduce
    // l'animazione di uscita) e solo a fine animazione si toglie davvero .open, cosi' la tendina
    // non sparisce di scatto
    function closeMenu(){
      if(!navlinks.classList.contains('open')) return;
      navlinks.classList.remove('open');
      navlinks.classList.add('closing');
      toggle.setAttribute('aria-expanded', 'false');
      // timeout invece di animationend: cosi' il menu si chiude comunque anche se
      // l'animazione viene saltata (prefers-reduced-motion) o interrotta
      setTimeout(function(){
        navlinks.classList.remove('closing');
      }, 280);
    }
    toggle.addEventListener('click', function(){
      if(navlinks.classList.contains('open')){
        closeMenu();
      } else {
        navlinks.classList.remove('closing');
        navlinks.classList.add('open');
        toggle.setAttribute('aria-expanded', 'true');
      }
    });
    navlinks.querySelectorAll('a').forEach(function(link){
      link.addEventListener('click', closeMenu);
    });
  });
}

function growmiInitHeaderScroll(){
  var header = document.querySelector('header');
  if(!header) return;
  var next = header.nextElementSibling;
  var overDarkHero = next && (next.classList.contains('ed-hero') || next.classList.contains('mise-hero'));
  if(!overDarkHero) return;
  function update(){ header.classList.toggle('at-top', window.scrollY < 12); }
  update();
  window.addEventListener('scroll', update, { passive:true });
}

document.addEventListener('DOMContentLoaded', growmiInitLang);
